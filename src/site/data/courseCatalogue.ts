/** OR within one group: no selection matches everything; otherwise any selected value matches. */
function matchesFacet(course: CourseRecord, key: FacetKey, selected: readonly string[]): boolean {
  const wanted = selected.filter(isResolvedCatalogueValue);
  if (selected.length === 0) return true;
  const values = getCourseFacetValues(course, key);
  return values.some((value) => wanted.some((item) => sameValue(item, value)));
}

/** A multi-grade course matches every grade it covers (Grade 11 finds a Grade 10–12 course). */
function matchesGrades(course: CourseRecord, grades: readonly number[]): boolean {
  if (grades.length === 0) return true;
  const covered = getCourseGrades(course);
  return grades.some((grade) => covered.includes(grade));
}

/** AND across groups, OR within a group. The single matching rule for cards and counts. */
export function matchesCatalogueFilters(course: CourseRecord, filters: CatalogueFilters): boolean {
  const query = normalizeCatalogueValue(filters.q).toLocaleLowerCase();
  const matchesQuery =
    query.length < 2 ||
    [
      course.title,
      course.subject ?? "",
      course.programType ?? "",
      isResolvedCatalogueValue(course.language) ? course.language : "",
    ].some((value) => normalizeCatalogueValue(value).toLocaleLowerCase().includes(query));

  return (
    matchesQuery &&
    matchesFacet(course, "subjects", filters.subjects) &&
    matchesFacet(course, "models", filters.models) &&
    matchesGrades(course, filters.grades) &&
    matchesFacet(course, "languages", filters.languages) &&
    matchesFacet(course, "programTypes", filters.programTypes)
  );
}

/**
 * How many courses would be listed if this option were the only one selected in its group,
 * with every other active filter (search, subjects, other groups) still applied.
 */
export function getCatalogueOptionCount(
  courses: readonly CourseRecord[],
  filters: CatalogueFilters,
  key: CatalogueFilterKey,
  value: CatalogueFilterValue,
): number {
  const onlyThisOption = { ...filters, [key]: [value] } as CatalogueFilters;
  return courses.filter((course) => matchesCatalogueFilters(course, onlyThisOption)).length;
}

export function sortCourses(
  courses: readonly CourseRecord[],
  sort: CatalogueFilters["sort"],
): CourseRecord[] {
  const lowest = (course: CourseRecord) => getCourseGrades(course)[0] ?? Number.MAX_SAFE_INTEGER;
  const highest = (course: CourseRecord) =>
    getCourseGrades(course).at(-1) ?? Number.MAX_SAFE_INTEGER;
  return [...courses].sort((a, b) => {
    // Lowest grade first; a single-grade course before a range starting at the same grade.
    if (sort === "grade")
      return (
        lowest(a) - lowest(b) ||
        highest(a) - highest(b) ||
        (a.displayOrder ?? Number.MAX_SAFE_INTEGER) - (b.displayOrder ?? Number.MAX_SAFE_INTEGER) ||
        a.title.localeCompare(b.title)
      );
    if (sort === "az")
      return (
        a.title.localeCompare(b.title) ||
        (a.displayOrder ?? Number.MAX_SAFE_INTEGER) - (b.displayOrder ?? Number.MAX_SAFE_INTEGER)
      );
    return (
      (a.displayOrder ?? Number.MAX_SAFE_INTEGER) - (b.displayOrder ?? Number.MAX_SAFE_INTEGER) ||
      a.title.localeCompare(b.title)
    );
  });
}

/** Difficulty labels on course cards (always written in full). */
const DIFFICULTY_LABELS: Record<string, string> = {
  "very easy": "Very Easy",
  easy: "Easy",
  moderate: "Moderate",
  hard: "Hard",
  "all levels": "All Levels",
};

/**
 * The level shown on a course card: a hand-added course's own level text (e.g. "Simple Level"),
 * otherwise the Live Level (e.g. "Level 2") for Live courses, and the
 * difficulty (Very Easy, Easy, Moderate or Hard) for all other courses. Undefined when the workbook has
 * no value for that course.
 */
export function getCourseLevelLabel(course: CourseRecord): string | undefined {
  if (course.levelLabel?.trim()) return course.levelLabel.trim();
  if (valueKey(course.learningModel ?? "") === "live") {
    return course.liveLevel?.trim() || undefined;
  }
  return DIFFICULTY_LABELS[valueKey(course.level ?? "")];
}

export function getCatalogueCourseByRouteSlug(slug: string): CourseRecord | undefined {
  return catalogueCourses.find((course) => course.routeSlug === slug);
}
